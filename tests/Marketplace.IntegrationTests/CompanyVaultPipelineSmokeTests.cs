    [Fact]
    public async Task ExtractionServiceFailureDoesNotCrashTheUpload()
    {
        string tempRoot = TempRoot();
        Directory.CreateDirectory(tempRoot);
        try
        {
            using WebApplicationFactory<Program> vaultFactory = factory.WithWebHostBuilder(builder =>
            {
                builder.ConfigureTestServices(services =>
                {
                    services.RemoveAll<IDocumentExtractionService>();
                    services.AddSingleton<IDocumentExtractionService, ThrowingExtractionService>();
                });
                builder.ConfigureAppConfiguration((_, configuration) => configuration.AddInMemoryCollection(
                    new Dictionary<string, string?> { ["Storage:UseLocalStorage"] = "true", ["Storage:LocalPath"] = tempRoot }));
            });
            (HttpClient client, Guid userId) = await CreateAuthenticatedSupplierAsync(vaultFactory);

            string fixturePath = Path.Combine(AppContext.BaseDirectory, "Fixtures", "vault", "certificat-onrc.pdf");
            using var fileContent = new ByteArrayContent(await File.ReadAllBytesAsync(fixturePath));
            using var form = new MultipartFormDataContent();
            form.Add(fileContent, "file", "certificat-onrc.pdf");

            // The OCR provider throws, but the upload must still succeed: the file is stored and the
            // document is saved as pending instead of a 500 crash + orphaned storage object.
            HttpResponseMessage upload = await client.PostAsync($"/api/v1/companies/{userId}/vault/documents", form);
            Assert.Equal(HttpStatusCode.OK, upload.StatusCode);
            VaultDocumentDto document = (await upload.Content.ReadFromJsonAsync<VaultDocumentDto>())!;
            Assert.False(document.Extracted);
            Assert.Equal(0, document.ChunkCount);

            using IServiceScope scope = vaultFactory.Services.CreateScope();
            MarketplaceDbContext db = scope.ServiceProvider.GetRequiredService<MarketplaceDbContext>();
            VaultDocument persisted = await db.VaultDocuments.AsNoTracking()
                .Include(item => item.Chunks)
                .SingleAsync(item => item.Id == document.Id);
            Assert.False(persisted.Extracted);
            Assert.Null(persisted.ExtractedMarkdown);
            Assert.Empty(persisted.Chunks);
            Assert.StartsWith("local://vault/", persisted.S3Url, StringComparison.Ordinal);

            string relativePath = persisted.S3Url["local://".Length..].Replace('/', Path.DirectorySeparatorChar);
            Assert.True(File.Exists(Path.Combine(tempRoot, relativePath)), "the file must still be stored");
        }
        finally
        {
            if (Directory.Exists(tempRoot)) Directory.Delete(tempRoot, recursive: true);
        }
    }

    private static WebApplicationFactory<Program> CreateVaultFactory(
        MarketplaceWebApplicationFactory baseFactory, string tempRoot) =>
        baseFactory.WithWebHostBuilder(builder =>
        {
            builder.ConfigureTestServices(services =>
            {
                services.RemoveAll<IDocumentExtractionService>();
                services.AddSingleton<IDocumentExtractionService, PdfPigDocumentExtractionService>();
            });
            builder.ConfigureAppConfiguration((_, configuration) => configuration.AddInMemoryCollection(
                new Dictionary<string, string?> { ["Storage:UseLocalStorage"] = "true", ["Storage:LocalPath"] = tempRoot }));
        });

    private static string TempRoot() => Path.Combine(Path.GetTempPath(), "compaspot-vault-" + Guid.NewGuid().ToString("N"));

    private static async Task<(HttpClient Client, Guid UserId)> CreateAuthenticatedSupplierAsync(WebApplicationFactory<Program> appFactory)
    {
        HttpClient client = appFactory.CreateClient(new() { BaseAddress = new Uri("https://localhost") });
        string email = $"vault-smoke-{Guid.NewGuid():N}@test.local";
        const string password = "Test123456!";
        Assert.Equal(HttpStatusCode.Created,
            (await client.PostAsJsonAsync("/api/v1/auth/register/supplier", new { email, password })).StatusCode);

        TokenResponse token = (await (await client.PostAsJsonAsync("/api/v1/auth/login", new { email, password }))
            .Content.ReadFromJsonAsync<TokenResponse>())!;
        Guid userId = UserId(token.AccessToken);
        client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", token.AccessToken);
        Assert.Equal(HttpStatusCode.OK,
            (await client.PutAsJsonAsync($"/api/v1/suppliers/{userId}", SupplierProfileRequest(email))).StatusCode);
        return (client, userId);
    }

    private static object SupplierProfileRequest(string email) => new
    {
        tradingName = "Companie smoke test vault", companyRegistrationNumber = $"J00/{Guid.NewGuid():N}", taxIdentifier = "RO123",
        contactPerson = "Owner test", contactEmail = email, phoneNumber = "0700000000", website = (string?)null,
        address = "Strada Test 1", city = "Iași", county = "Iași", latitude = (decimal?)null,
        longitude = (decimal?)null, description = "Profil pentru smoke test-ul pipeline-ului Company Vault"
    };

    private static Guid UserId(string accessToken)
    {
        string payloadPart = accessToken.Split('.')[1];
        string payload = Encoding.UTF8.GetString(Convert.FromBase64String(
            payloadPart.PadRight(payloadPart.Length + (4 - payloadPart.Length % 4) % 4, '=').Replace('-', '+').Replace('_', '/')));
        return Guid.Parse(JsonDocument.Parse(payload).RootElement.GetProperty("sub").GetString()!);
    }

    /// <summary>Real text extraction from the actual fixture PDF bytes, using the same PdfPig library the
    /// Azure path uses for page counting (UglyToad.PdfPig, package id "PdfPig").</summary>
    private sealed class PdfPigDocumentExtractionService : IDocumentExtractionService
    {
        public Task<DocumentExtractionResult> ExtractAsync(Stream document, string fileName, CancellationToken cancellationToken)
        {
            using MemoryStream buffer = new();
            if (document.CanSeek) document.Position = 0;
            document.CopyTo(buffer);
            buffer.Position = 0;

            using PdfDocument pdf = PdfDocument.Open(buffer);
            List<ExtractedPage> pages = [];
            StringBuilder fullText = new();
            foreach (Page page in pdf.GetPages())
            {
                cancellationToken.ThrowIfCancellationRequested();
                string text = page.Text;
                if (fullText.Length > 0) fullText.AppendLine();
                fullText.Append(text);
                pages.Add(new ExtractedPage(page.Number, text, []));
            }
            return Task.FromResult(new DocumentExtractionResult(fullText.ToString(), pages));
        }
    }

    /// <summary>Simulates the OCR provider going down / rejecting a corrupt payload mid-pipeline.</summary>
    private sealed class ThrowingExtractionService : IDocumentExtractionService
    {
        public Task<DocumentExtractionResult> ExtractAsync(Stream document, string fileName, CancellationToken cancellationToken) =>
            throw new IOException("Serviciul de extragere a eșuat (simulat).");
    }

