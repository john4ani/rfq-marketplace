/// <summary>
/// Vault pipeline smoke tests against real fixture PDFs (tests/Fixtures/vault/*.pdf, generated by
/// scripts/generate-vault-fixtures.ps1). The real CompanyVaultService runs the whole pipeline —
/// Upload → object storage (local disk) → text extraction → Markdown → chunking → Postgres — over the
/// actual bytes of each fixture. The only swapped dependency is the OCR provider: instead of calling
/// the live Azure Document Intelligence endpoint (needs credentials), <see cref="PdfPigDocumentExtractionService"/>
/// extracts the text with PdfPig — the same library the Azure path already uses for page counting — so
/// the extracted text, diacritics and chunking are validated against the real file content.
/// </summary>
[Collection(IntegrationTestGroup.Name)]
