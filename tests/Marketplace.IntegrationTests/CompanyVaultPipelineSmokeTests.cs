    private readonly MarketplaceWebApplicationFactory factory;
    public CompanyVaultPipelineSmokeTests(MarketplaceWebApplicationFactory factory) => this.factory = factory;

    private static readonly char[] LowercaseDiacritics = ['ș', 'ț', 'ă', 'î', 'â'];

    public static TheoryData<string> FixturePdfs { get; } = new()
    {
        "certificat-onrc.pdf",
        "fisa-tehnica.pdf",
        "contract-experienta.pdf"
    };

    /// <summary>Single-word phrases (robust against Chrome's text-run splitting) proving the diacritics arrived intact.</summary>
    private static readonly Dictionary<string, string[]> ExpectedDiacriticPhrases = new()
    {
        ["certificat-onrc.pdf"] = ["României", "desfășura", "înmatriculată", "începând", "Școlii", "activități"],
        ["fisa-tehnica.pdf"] = ["FIȘĂ", "performanță", "instrucțiunilor", "clădirilor", "construcții", "păstrează"],
        ["contract-experienta.pdf"] = ["EXPERIENȚĂ", "Bălțești", "Ținând", "șantier", "începere", "lucrărilor"]
    };

    private static readonly Dictionary<string, int> ExpectedMinChunks = new()
    {
        ["certificat-onrc.pdf"] = 1,
        ["fisa-tehnica.pdf"] = 2, // >800 chars → the overlapping chunker must produce at least 2 fragments
        ["contract-experienta.pdf"] = 1
    };

    [Theory]
    [MemberData(nameof(FixturePdfs))]
    public async Task RealPdfFlowsThroughUploadExtractionStorageAndChunking(string fixtureName)
    {
        string tempRoot = Path.Combine(Path.GetTempPath(), "compaspot-vault-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempRoot);
        try
        {
            using WebApplicationFactory<Program> vaultFactory = CreateVaultFactory(factory, tempRoot);
            (HttpClient client, Guid userId) = await CreateAuthenticatedSupplierAsync(vaultFactory);

            string fixturePath = Path.Combine(AppContext.BaseDirectory, "Fixtures", "vault", fixtureName);
            Assert.True(File.Exists(fixturePath), $"Fixture not copied to the test output: {fixturePath}");
            byte[] pdfBytes = await File.ReadAllBytesAsync(fixturePath);
            Assert.StartsWith("%PDF-", Encoding.ASCII.GetString(pdfBytes[..5]));

            // Upload → storage → extraction → markdown → chunking → Postgres, all in one request.
            using var fileContent = new ByteArrayContent(pdfBytes);
            using var form = new MultipartFormDataContent();
            form.Add(fileContent, "file", fixtureName);
            HttpResponseMessage upload = await client.PostAsync($"/api/v1/companies/{userId}/vault/documents", form);
            Assert.Equal(HttpStatusCode.OK, upload.StatusCode);
            VaultDocumentDto document = (await upload.Content.ReadFromJsonAsync<VaultDocumentDto>())!;
            Assert.Equal(fixtureName, document.FileName);
            Assert.True(document.Extracted, "the fixture should be marked as extracted after the pipeline runs");
            Assert.True(document.PageCount > 0);
            Assert.True(document.ChunkCount >= ExpectedMinChunks[fixtureName],
                $"expected at least {ExpectedMinChunks[fixtureName]} chunks, got {document.ChunkCount}");

            // Persistence: the stored file must exist on the local storage root and match the fixture bytes.
            using IServiceScope scope = vaultFactory.Services.CreateScope();
            MarketplaceDbContext db = scope.ServiceProvider.GetRequiredService<MarketplaceDbContext>();
            VaultDocument persisted = await db.VaultDocuments.AsNoTracking()
                .Include(item => item.Chunks)
                .SingleAsync(item => item.Id == document.Id);
            Assert.True(persisted.Extracted);
            Assert.Equal(document.PageCount, persisted.PageCount);
            Assert.False(string.IsNullOrWhiteSpace(persisted.ExtractedMarkdown));
            Assert.Equal(document.ChunkCount, persisted.Chunks.Count);
            Assert.StartsWith("local://vault/", persisted.S3Url, StringComparison.Ordinal);

            string relativePath = persisted.S3Url["local://".Length..].Replace('/', Path.DirectorySeparatorChar);
            string storedPath = Path.Combine(tempRoot, relativePath);
            Assert.True(File.Exists(storedPath), "the uploaded PDF must be physically present on the local storage root");
            Assert.Equal(pdfBytes, await File.ReadAllBytesAsync(storedPath));

            // Diacritics: extraction → markdown → chunks → Postgres round-trip must keep the exact Unicode chars.
            string markdown = persisted.ExtractedMarkdown!;
            foreach (char diacritic in LowercaseDiacritics)
                Assert.Contains(diacritic, markdown);
            foreach (string phrase in ExpectedDiacriticPhrases[fixtureName])
                Assert.Contains(phrase, markdown);
            string chunkText = string.Concat(persisted.Chunks.Select(chunk => chunk.Content));
            foreach (char diacritic in LowercaseDiacritics)
                Assert.Contains(diacritic, chunkText);

            // The SPA contract (GET /vault) reports the processed document the same way.
            HttpResponseMessage list = await client.GetAsync($"/api/v1/companies/{userId}/vault");
            Assert.Equal(HttpStatusCode.OK, list.StatusCode);
            VaultDocumentDto[] listed = (await list.Content.ReadFromJsonAsync<VaultDocumentDto[]>() ?? [])!;
            VaultDocumentDto listedDocument = Assert.Single(listed, item => item.Id == document.Id);
            Assert.True(listedDocument.Extracted);
            Assert.Equal(document.ChunkCount, listedDocument.ChunkCount);
        }
        finally
        {
            if (Directory.Exists(tempRoot)) Directory.Delete(tempRoot, recursive: true);
        }
    }

